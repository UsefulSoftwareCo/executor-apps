#!/usr/bin/env python3
"""Regenerates spec.ts from operations.txt: a hand-written OpenAPI 3.0 document of the
Databricks workspace REST API, written from https://docs.databricks.com/api/workspace/introduction
(Databricks publishes no OpenAPI document). Usage: python3 -I packages/databricks/generate.py"""
import json, re, pathlib

here = pathlib.Path(__file__).parent
TYPES = {"s": "string", "i": "integer", "b": "boolean", "o": "object", "a": "array"}

def field(spec):
    required = spec.endswith("!")
    spec = spec.rstrip("!")
    name, _, t = spec.partition(":")
    kind = TYPES[t or "s"]
    schema = {"type": kind}
    if kind == "array": schema["items"] = {}
    if kind == "object": schema["additionalProperties"] = True
    return name, schema, required

def fields(text):
    return [field(p) for p in text.split(",") if p]

paths, tags, reads = {}, [], []
for line in (here / "operations.txt").read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    tag, op, method, path, summary, query, body = line.split("|")
    if tag not in tags: tags.append(tag)
    read_post = method.endswith("R")
    method = method.rstrip("R")
    if read_post: reads.append(op)
    operation = {"operationId": op, "tags": [tag], "summary": summary, "parameters": [], "responses": {"200": {"description": "OK", "content": {"application/json": {"schema": {"type": "object", "additionalProperties": True}}}}}}
    for name in re.findall(r"\{(\w+)\}", path):
        operation["parameters"].append({"name": name, "in": "path", "required": True, "schema": {"type": "string"}})
    for name, schema, required in fields(query):
        operation["parameters"].append({"name": name, "in": "query", "required": required, "schema": schema})
    if not operation["parameters"]: del operation["parameters"]
    props = fields(body)
    if props:
        operation["requestBody"] = {"required": any(r for _, _, r in props), "content": {"application/json": {"schema": {
            "type": "object", "additionalProperties": True,
            "properties": {n: s for n, s, _ in props},
            **({"required": [n for n, _, r in props if r]} if any(r for _, _, r in props) else {})}}}}
    paths.setdefault(path, {})[method.lower()] = operation

doc = {"openapi": "3.0.0", "info": {"title": "Databricks workspace REST API", "version": "1.0.0", "description": "Hand-written from docs.databricks.com/api/workspace."},
       "servers": [{"url": "https://workspace.cloud.databricks.com"}], "tags": [{"name": t} for t in tags], "paths": paths}
out = "// Generated by generate.py from operations.txt. Do not edit.\n"
out += f"export const document = JSON.parse({json.dumps(json.dumps(doc, separators=(',', ':')))});\n"
out += f"export const readOperations: readonly string[] = {json.dumps(reads)};\n"
(here / "spec.ts").write_text(out)
print(len(sum((list(v.values()) for v in paths.values()), [])), "operations")
