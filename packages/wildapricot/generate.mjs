// Regenerates spec.ts: an OpenAPI 3.0 conversion (swagger2openapi) of WildApricot's official Admin
// API Swagger 2.0 definition, published by the vendor on SwaggerHub.
// Usage: node packages/wildapricot/generate.mjs   (needs network and npx)
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const url = "https://api.swaggerhub.com/apis/WildApricot/wild-apricot_public_api/7.24.0";
const dir = mkdtempSync(join(tmpdir(), "wildapricot-"));
const input = join(dir, "admin.json");
const output = join(dir, "admin.oas3.json");
writeFileSync(input, Buffer.from(await (await fetch(url)).arrayBuffer()));
execFileSync("npx", ["--yes", "swagger2openapi", "--patch", "-o", output, input], { stdio: "inherit" });

const doc = JSON.parse(readFileSync(output, "utf8"));
// Tokens are minted by the provider's client-credentials grant; the bearer credential is injected.
delete doc.security;
delete doc.components?.securitySchemes;
for (const item of Object.values(doc.paths))
  for (const op of Object.values(item)) if (op && typeof op === "object") delete op.security;
// swagger2openapi leaves a stray `name` on converted body parameters; drop it from request bodies.
for (const body of Object.values(doc.components?.requestBodies ?? {})) delete body.name;
doc.servers = [{ url: "https://api.wildapricot.org/v2.2" }];

writeFileSync(
  new URL("./spec.ts", import.meta.url),
  `// Generated by generate.mjs from WildApricot's official Admin API Swagger document. Do not edit.\nexport const document = JSON.parse(${JSON.stringify(JSON.stringify(doc))});\n`,
);
