// Regenerates spec.ts: an OpenAPI 3.0 conversion (swagger2openapi) of Anthology's official
// Blackboard Learn Swagger 2.0 document, published at
// https://developer.blackboard.com/portal/docs/apis/learn-swagger.json.
// Usage: node packages/blackboard/generate.mjs   (needs network and npx)
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const url = "https://developer.blackboard.com/portal/docs/apis/learn-swagger.json";
const dir = mkdtempSync(join(tmpdir(), "blackboard-"));
const input = join(dir, "learn.json");
const output = join(dir, "learn.oas3.json");
writeFileSync(input, Buffer.from(await (await fetch(url)).arrayBuffer()));
execFileSync("npx", ["--yes", "swagger2openapi", "--patch", "-o", output, input], { stdio: "inherit" });

const doc = JSON.parse(readFileSync(output, "utf8"));
// The OAuth token endpoint is exchanged in index.ts from the application key and secret.
for (const path of Object.keys(doc.paths)) if (path.includes("/oauth2/")) delete doc.paths[path];
delete doc.security;
delete doc.components?.securitySchemes;
for (const item of Object.values(doc.paths))
  for (const op of Object.values(item)) if (op && typeof op === "object") delete op.security;
doc.servers = [{ url: "https://blackboard.example.com" }];
doc.info = { title: "Blackboard Learn REST API", version: doc.info.version };

writeFileSync(
  new URL("./spec.ts", import.meta.url),
  `// Generated by generate.mjs from Anthology's official Blackboard Learn Swagger document. Do not edit.\nexport const document = JSON.parse(${JSON.stringify(JSON.stringify(doc))});\n`,
);
