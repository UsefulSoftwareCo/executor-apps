const patches = multiScheme.map((entry) => {
  const [path, method] = entry.split(" ") as [string, string];
  return {
    op: "replace" as const,
    path: `/paths/${path.replaceAll("~", "~0").replaceAll("/", "~1")}/${method}/security`,
    value: [{ apiKeyInHeader: [] }],
  };
});

export const options = {
  source: { url: "https://api.centralstationcrm.net/api-docs/v1/swagger.json" },
  allowedOrigin: "https://api.centralstationcrm.net",
  securitySchemes: { apiKeyInHeader: { type: "apiKey", in: "header", name: "X-apikey" } },
  methods: { apiKey: [{ scheme: "apiKeyInHeader", field: "token", part: "value", prefix: "" }] },
  oauth: [],
  patches,
} satisfies OpenapiToolNamesOptions;
