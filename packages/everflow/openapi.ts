export const specOptions = (name: string) =>
  ({
    source: { url: `https://developers.everflow.io/openapi/${name}.yaml` },
    allowedOrigin: defaultOrigin,
    baseUrl: `${defaultOrigin}/v1`,
    securitySchemes: { "API Key": { type: "apiKey", in: "header", name: "X-Eflow-Api-Key" } },
    methods: { apiKey: [{ scheme: "API Key", field: "token", part: "value", prefix: "" }] },
    oauth: [],
  }) satisfies OpenapiToolNamesOptions;

