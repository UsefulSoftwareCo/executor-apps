#!/usr/bin/env python3
"""Regenerates spec.ts: one OpenAPI 3.0 document bundled from the per-resource files in
https://github.com/snowflakedb/snowflake-rest-api-specs (Snowflake's official REST API specs).
Usage: uv run --with pyyaml python -I packages/snowflake/generate.py"""
import json, re, sys, urllib.request, pathlib

SHA = "990e25d97236a11826c9eed40e587c2b859e5680"  # pinned upstream commit; bump to refresh
API = f"https://api.github.com/repos/snowflakedb/snowflake-rest-api-specs/contents/specifications?ref={SHA}"
RAW = f"https://raw.githubusercontent.com/snowflakedb/snowflake-rest-api-specs/{SHA}/specifications/"
import yaml

def get(url):
    with urllib.request.urlopen(url) as r:
        return r.read().decode()

files = [f["name"] for f in json.loads(get(API)) if f["name"].endswith(".yaml")]
docs = {f: yaml.safe_load(get(RAW + f)) for f in files}

def pascal(stem):
    return "".join(p.capitalize() for p in stem.split("-"))

def camel(stem):
    p = pascal(stem)
    return p[0].lower() + p[1:]

SECTIONS = ["schemas", "parameters", "responses", "headers", "requestBodies", "examples"]

def rename(file, section, name):
    return f"{pascal(file[:-5])}_{name}"

def rewrite(node, file):
    if isinstance(node, dict):
        out = {}
        for k, v in node.items():
            if k == "$ref" and isinstance(v, str):
                target, _, frag = v.partition("#")
                tfile = target.removeprefix("./") or file
                m = re.match(r"/components/(\w+)/(.+)$", frag)
                if not m:
                    raise SystemExit(f"unsupported ref {v} in {file}")
                if m.group(1) == "securitySchemes":
                    out[k] = "#/components/securitySchemes/bearer"
                else:
                    out[k] = f"#/components/{m.group(1)}/{rename(tfile, m.group(1), m.group(2))}"
            else:
                out[k] = rewrite(v, file)
        return out
    if isinstance(node, list):
        return [rewrite(v, file) for v in node]
    return node

paths, components = {}, {s: {} for s in SECTIONS}
seen_ops = {}
for file, doc in docs.items():
    stem = file[:-5]
    for section in SECTIONS:
        for name, value in (doc.get("components", {}).get(section) or {}).items():
            components[section][rename(file, section, name)] = rewrite(value, file)
    for path, item in (doc.get("paths") or {}).items():
        item = rewrite(item, file)
        if path in paths:
            raise SystemExit(f"duplicate path {path} in {file}")
        for method, op in item.items():
            if not isinstance(op, dict) or "responses" not in op:
                continue
            op.pop("security", None)
            op["tags"] = [stem]
            oid = op.get("operationId")
            if oid:
                seen_ops.setdefault(oid, []).append((path, method))
        paths[path] = item

# Disambiguate operation ids shared by several resources with the owning resource.
for oid, uses in seen_ops.items():
    if len(uses) > 1:
        for path, method in uses:
            op = paths[path][method]
            op["operationId"] = f"{op['tags'][0].replace('-', '_')}_{oid}"

document = {
    "openapi": "3.0.0",
    "info": {"title": "Snowflake REST APIs", "version": "2.0.0",
             "description": "Bundled from snowflakedb/snowflake-rest-api-specs."},
    "servers": [{"url": "https://org-account.snowflakecomputing.com"}],
    "tags": [{"name": d[:-5]} for d in docs if docs[d].get("paths")],
    "paths": paths,
    "components": {**{k: v for k, v in components.items() if v},
                   "securitySchemes": {"bearer": {"type": "http", "scheme": "bearer"}}},
}
text = json.dumps(document, separators=(",", ":"), default=str)
out = pathlib.Path(__file__).with_name("spec.ts")
out.write_text("// Generated by generate.py from Snowflake's official REST API specifications "
               f"at commit {SHA}. Do not edit.\n"
               f"export const document = JSON.parse({json.dumps(text)});\n")
print(len(paths), "paths", len(text), "bytes")
