// Every eWay-CRM instance has its own Web Service address, e.g. https://free.eway-crm.com/31994.
export const serviceUrl = (input: string) => {
  const url = new URL(/^https?:\/\//i.test(input.trim()) ? input.trim() : `https://${input.trim()}`);
  if (url.protocol !== "https:" || !url.hostname.endsWith(".eway-crm.com") || url.username !== "" || url.password !== "" || url.search !== "" || url.hash !== "")
    throw new Error("Enter the Web Service address on eway-crm.com, e.g. free.eway-crm.com/31994.");
  return `${url.origin}${url.pathname.replace(/\/+$/, "")}`;
};

