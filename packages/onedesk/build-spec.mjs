// Regenerates spec.ts from OneDesk's published OpenAPI document.
// OneDesk nests each tag's schemas under components.schemas.<tag>.components.schemas and
// references them as #/components/schemas/<tag>/components/schemas/<Name>, which Executor's
// compiler rejects. This hoists them to #/components/schemas/<tag>__<Name>.
// Usage: node packages/onedesk/build-spec.mjs
import { writeFileSync } from "node:fs";

const url = "https://onedesk.com/public-api/onedesk-public-api.json";
const doc = await (await fetch(url)).json();
const flat = {};
for (const [tag, group] of Object.entries(doc.components.schemas)) {
  for (const [name, schema] of Object.entries(group.components?.schemas ?? {})) flat[`${tag}__${name}`] = schema;
}
const text = JSON.stringify({ ...doc, components: { ...doc.components, schemas: flat } }).replace(
  /#\/components\/schemas\/([^/"]+)\/components\/schemas\/([^/"]+)/g,
  "#/components/schemas/$1__$2",
);
writeFileSync(
  new URL("./spec.ts", import.meta.url),
  `// Generated by build-spec.mjs from ${url}. Do not edit.\nimport type { JsonObject } from "apps";\n\nexport const spec: JsonObject = ${text};\n`,
);
