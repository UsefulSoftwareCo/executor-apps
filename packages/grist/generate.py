# Regenerates spec.ts from Grist's official API reference (gristlabs/grist-help api/grist.yml).
# The enterprise SCIM paths are external $ref files and are dropped. Usage: python3 generate.py
import json, os, urllib.request, yaml

url = "https://raw.githubusercontent.com/gristlabs/grist-help/master/api/grist.yml"
doc = yaml.safe_load(urllib.request.urlopen(url).read())
doc["paths"] = {p: v for p, v in doc["paths"].items() if not p.startswith("/scim")}
doc["servers"] = [{"url": "https://docs.getgrist.com/api"}]
text = json.dumps(doc, separators=(",", ":"))
assert '"$ref":"./' not in text, "external refs remain"
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "spec.ts")
with open(out, "w") as f:
    f.write("// Generated by generate.py from Grist's official API reference. Do not edit.\n")
    f.write("export const document = JSON.parse(%s);\n" % json.dumps(text))
print(len(doc["paths"]), "paths")
