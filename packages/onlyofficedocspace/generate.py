# Regenerates spec.ts from ONLYOFFICE's official DocSpace OpenAPI document
# (https://github.com/ONLYOFFICE/api.onlyoffice.com/blob/master/openapi/docspace/docspace-backend.yaml).
# Edits: the server is a placeholder (index.ts routes calls to the account's portal), and each
# operation's alternative security schemes are reduced to the API key. Usage:
#   python3 -I packages/onlyofficedocspace/generate.py <path to docspace-backend.yaml>
import json, sys, pathlib, yaml
doc = yaml.safe_load(open(sys.argv[1]))
doc["servers"] = [{"url": "https://docspace.example.com"}]
doc["components"]["securitySchemes"] = {"ApiKeyBearer": {"type": "apiKey", "in": "header", "name": "Authorization"}}
doc["security"] = [{"ApiKeyBearer": []}]
for item in doc["paths"].values():
    for m, op in item.items():
        if isinstance(op, dict) and "security" in op and op["security"]:
            op["security"] = [{"ApiKeyBearer": []}]
out = "// Generated by generate.py; do not edit.\nexport const document = JSON.parse(%s);\n" % json.dumps(json.dumps(doc, separators=(",", ":")))
pathlib.Path(__file__).with_name("spec.ts").write_text(out)
