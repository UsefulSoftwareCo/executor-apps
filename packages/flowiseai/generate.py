# Regenerates spec.ts from Flowise's official Swagger source (packages/api-documentation/src/yml/swagger.yml
# in FlowiseAI/Flowise). The source omits the `openapi`, `info` and `servers` fields, so they are added here.
# Usage: python3 generate.py
import json, os, urllib.request, yaml

url = "https://raw.githubusercontent.com/FlowiseAI/Flowise/543800562ef7a842ae2921a72fb549082eb38678/packages/api-documentation/src/yml/swagger.yml"
doc = yaml.safe_load(urllib.request.urlopen(url).read())
doc = {
    "openapi": "3.0.0",
    "info": {"title": "Flowise API", "version": "1.0.0"},
    "servers": [{"url": "https://cloud.flowiseai.com/api/v1"}],
    **doc,
}
text = json.dumps(doc, separators=(",", ":"), default=str)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "spec.ts")
with open(out, "w") as f:
    f.write("// Generated by generate.py from Flowise's official swagger.yml. Do not edit.\n")
    f.write("export const document = JSON.parse(%s);\n" % json.dumps(text))
print(len(doc["paths"]), "paths")
