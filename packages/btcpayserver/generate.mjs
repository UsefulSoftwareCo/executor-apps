// Regenerates spec.ts from BTCPay Server's official Greenfield OpenAPI document
// (https://docs.btcpayserver.org/API/Greenfield/v1/swagger.json). Changes: the document lists
// `API_Key` and `Basic` inside one security requirement (meaning both), but they are alternatives, so
// each operation is reduced to API_Key. Usage: node packages/btcpayserver/generate.mjs
import { writeFileSync } from "node:fs";
const res = await fetch("https://docs.btcpayserver.org/API/Greenfield/v1/swagger.json");
const doc = await res.json();
for (const item of Object.values(doc.paths))
  for (const op of Object.values(item)) {
    if (!op || typeof op !== "object" || !Array.isArray(op.security)) continue;
    op.security = op.security.map((req) => (req.API_Key ? { API_Key: req.API_Key } : req));
  }
// Top-level security: the vendor's text says "either Basic or API key"; normalize to API_Key alone.
doc.security = [{ API_Key: [] }];
// Confirmed [AllowAnonymous] in BTCPay's GreenfieldOfferingController.cs; the spec omits security: [] there.
for (const [path, methods] of [
  ["/api/v1/plan-checkout/{checkoutId}", ["get", "post"]],
  ["/api/v1/subscriber-portal/{portalSessionId}", ["get"]],
])
  for (const m of methods) doc.paths[path][m].security = [];
delete doc.components.securitySchemes.Basic;
const out = `// Generated by generate.mjs; do not edit.\nexport const document = JSON.parse(${JSON.stringify(JSON.stringify(doc))});\n`;
writeFileSync(new URL("./spec.ts", import.meta.url), out);
