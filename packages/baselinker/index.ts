type Fetch = typeof fetch;

// Every BaseLinker method is a form POST of `method` and a JSON `parameters` string.
async function call(fetcher: Fetch, signal: AbortSignal, token: string, method: string, parameters: unknown) {
  const response = await fetcher(endpoint, {
    method: "POST",
    signal,
    headers: { "X-BLToken": token, "content-type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ method, parameters: JSON.stringify(parameters ?? {}) }).toString(),
  });
  if (!response.ok) throw new Error(`BaseLinker ${method} failed with HTTP ${response.status}`);
  const body = (await response.json()) as { status?: string; error_code?: string; error_message?: string };
  if (body.status !== "SUCCESS") {
    throw new Error(`BaseLinker ${method} failed: ${body.error_code ?? "ERROR"} ${body.error_message ?? ""}`.trim());
  }
  return body;
}

