type Account = { fields: { token: string } };

const tools = (account: Account, signal: AbortSignal) =>
  router(
    Object.fromEntries(
      methods.map(([method, kind, summary]) => {
        const description = `${summary}. Calls the BaseLinker API method ${method}; pass its documented request parameters as the parameters object (https://api.baselinker.com/index.php?method=${method}). Returns the response fields alongside status.`;
        const input = object({ parameters: json().optional() });
        const run = ({ fetch }: { fetch: Fetch }, { parameters }: { parameters?: unknown }) =>
          call(fetch, signal, account.fields.token, method, parameters);
        return [
          method,
          kind === "query"
            ? query({ description, input }, run)
            : mutation({ description, input, approval: always() }, run),
        ];
      }),
    ),
  );

export default defineApp({ user: { accounts: { baselinker: baselinker.many() } }, icons }, async ({ user, signal }) => ({
  tools: router(await accountRouter(user?.accounts.baselinker ?? [], (account) => tools(account, signal), { signal }), {
    title: "BaseLinker",
    description:
      "E-commerce operations hub: orders, order returns, inventory catalogs and stock, invoices, couriers and packages, and external storages.",
    instructions:
      "Each tool maps to one BaseLinker API method and takes a `parameters` object with that method's documented fields. The API allows 100 requests per minute per token.",
    icons,
  }),
}));
