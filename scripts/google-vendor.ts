// Copies Google tool sources into the packages that use them, so each stays self-contained (the
// feed bundles only a package's own directory):
// - the single-product packages' generated-tool sources into packages/google/products, so the
//   all-in-one Google package reuses them;
// - the curated tools in shared/google-tools into packages/google/tools and into each
//   single-product package's tools/.
// Run after changing any of the sources below.
// Usage: node scripts/google-vendor.ts [--check]   (--check fails when a copy is out of date)
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const check = process.argv.includes("--check");

/** Mount key in packages/google/products → source package and the files it needs. */
const products: Record<string, { readonly from: string; readonly files: readonly string[] }> = {
  gmail: { from: "gmail", files: ["openapi.ts", "openapi.json"] },
  calendar: { from: "google-calendar", files: ["openapi.ts", "calendar-openapi.json"] },
  drive: { from: "google-drive", files: ["openapi.ts", "drive-openapi.json"] },
  sheets: { from: "google-sheets", files: ["openapi.ts", "openapi.json"] },
  docs: { from: "google-docs", files: ["tools.ts"] },
  slides: { from: "google-slides", files: ["tools.ts"] },
  forms: { from: "google-forms", files: ["openapi.ts", "openapi.json"] },
  tasks: { from: "google-tasks", files: ["openapi.ts", "openapi.json"] },
  contacts: { from: "google-contacts", files: ["openapi.ts", "openapi.json"] },
  meet: { from: "google-meet", files: ["tools.ts"] },
  photos: { from: "google-photos", files: ["openapi.ts", "openapi.json", "picker-openapi.json"] },
};

/** Package → the curated tool modules it mounts; shared.ts goes with every set. */
const curated: Record<string, readonly string[]> = {
  google: ["gmail.ts", "calendar.ts", "drive.ts", "sheets.ts", "people.ts", "tasks.ts"],
  gmail: ["gmail.ts"],
  "google-calendar": ["calendar.ts"],
  "google-drive": ["drive.ts"],
  "google-sheets": ["sheets.ts"],
  "google-contacts": ["people.ts"],
  "google-tasks": ["tasks.ts"],
};

const notice = (from: string) => `// Generated by scripts/google-vendor.ts from ${from}; edit the original and rerun it.\n`;
const copy = (from: string, file: string) => {
  const content = readFileSync(join(root, from, file), "utf8");
  return file.endsWith(".ts") ? notice(from) + content : content;
};

/** Each generated directory and the files it must hold, by path inside it. */
const targets = new Map<string, Map<string, string>>();
const productFiles = new Map<string, string>();
for (const [key, { from, files }] of Object.entries(products))
  for (const file of files) productFiles.set(join(key, file), copy(join("packages", from), file));
targets.set("packages/google/products", productFiles);
for (const [name, files] of Object.entries(curated))
  targets.set(
    `packages/${name}/tools`,
    new Map(["shared.ts", ...files].map((file) => [file, copy("shared/google-tools", file)])),
  );

const present = (dir: string) =>
  existsSync(dir)
    ? readdirSync(dir, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => join(entry.parentPath.slice(dir.length + 1), entry.name))
    : [];

if (check) {
  const stale: string[] = [];
  for (const [dir, expected] of targets) {
    const target = join(root, dir);
    for (const [path, content] of expected) {
      const file = join(target, path);
      if (!existsSync(file) || readFileSync(file, "utf8") !== content) stale.push(join(dir, path));
    }
    for (const path of present(target)) if (!expected.has(path)) stale.push(`${join(dir, path)} (not generated)`);
  }
  if (stale.length > 0) {
    console.error(`Generated Google sources are out of date: ${stale.join(", ")}. Run node scripts/google-vendor.ts.`);
    process.exit(1);
  }
  console.log(`Generated Google sources are up to date (${[...targets.values()].reduce((n, m) => n + m.size, 0)} files)`);
} else {
  for (const [dir, expected] of targets) {
    const target = join(root, dir);
    rmSync(target, { recursive: true, force: true });
    for (const [path, content] of expected) {
      const file = join(target, path);
      mkdirSync(join(file, ".."), { recursive: true });
      writeFileSync(file, content);
    }
    console.log(`wrote ${expected.size} files to ${dir}`);
  }
}
